"""Тематические звуки игры.

Использует стандартный модуль winsound (только Windows).
На других ОС звуки автоматически отключаются, игра работает как обычно.

Все звуки играются в отдельном daemon-потоке, потому что winsound.Beep
блокирующий и иначе «замораживал» бы сюжетные паузы.

Каждый звук — это короткая последовательность (частота_Гц, длительность_мс).
Если частота <= 0 — вместо писка просто пауза.
"""

import threading
import time

try:
    import winsound
    _SUPPORTED = True
except ImportError:          # Linux / macOS / PyPy без winsound
    winsound = None
    _SUPPORTED = False

_user_enabled = True          # пользовательская настройка (клавиша s)


# ------------------------------------------------------------
#                       управление
# ------------------------------------------------------------

def is_supported():
    """Поддерживает ли платформа звук (winsound есть?)."""
    return _SUPPORTED


def is_enabled():
    """Включён ли звук прямо сейчас (и вообще возможен ли)."""
    return _SUPPORTED and _user_enabled


def toggle():
    """Переключить звук. Возвращает новое состояние."""
    global _user_enabled
    _user_enabled = not _user_enabled
    return is_enabled()


def status_text():
    """Строка для интерфейса: что сейчас со звуком."""
    if not _SUPPORTED:
        return 'Звук недоступен на этой ОС (winsound — только Windows).'
    return 'Звук включён.' if _user_enabled else 'Звук выключен.'


# ------------------------------------------------------------
#                     внутренняя кухня
# ------------------------------------------------------------

def _play(seq, volume_scale=1.0):
    """Проиграть последовательность (freq, duration_ms) в фоне."""
    if not is_enabled():
        return

    def run():
        for freq, dur in seq:
            try:
                if freq <= 0:
                    time.sleep(dur / 1000.0)
                else:
                    winsound.Beep(int(freq), int(dur))
            except RuntimeError:
                # Бывает, если система не может выделить звуковое устройство.
                return

    threading.Thread(target=run, daemon=True).start()


# ------------------------------------------------------------
#                       сами звуки
# ------------------------------------------------------------

def step():
    """Короткий шаг/клик — переход между локациями."""
    _play([(440, 40)])


def ambient_shop():
    """Мрачный гул магазина — при входе в локацию."""
    _play([(120, 220), (-1, 60), (90, 260)])


def eat_can():
    """Чавканье — открываем и едим банку."""
    _play([(180, 90), (140, 90), (200, 90), (120, 200)])


def note_found():
    """Найдена записка — тихий «дзинь»."""
    _play([(880, 90), (1175, 140)])


def item_found():
    """Найден предмет — восходящий аккорд."""
    _play([(660, 90), (880, 120)])


def fight_hit():
    """Удар в бою — резкий низкий + металлический щелчок."""
    _play([(140, 70), (1000, 50), (140, 70)])


def hurt():
    """Игрок ранен — нисходящий стон."""
    _play([(320, 110), (240, 130), (180, 180)])


def death():
    """Смерть — «падение в темноту»."""
    _play([(700, 140), (560, 140), (420, 180),
           (300, 240), (200, 320), (120, 500)])


def win():
    """Победа — фанфарный аккорд C-E-G-C."""
    _play([(523, 150), (659, 150), (784, 150), (1046, 400)])


def error():
    """Некорректный ввод — короткий «бз-з»."""
    _play([(200, 180)])


def alarm():
    """Сигнализация (шкаф в комнате охраны)."""
    _play([(900, 120), (-1, 80), (900, 120), (-1, 80), (900, 200)])


def chudo_magic():
    """«Чудо сработало» — мягкие высокие переливы."""
    _play([(659, 120), (784, 120), (988, 120), (1319, 300)])